import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';

enum AppLocale { id, en }

final localeProvider = StateNotifierProvider<LocaleNotifier, AppLocale>((ref) => LocaleNotifier());

class LocaleNotifier extends StateNotifier<AppLocale> {
  LocaleNotifier() : super(AppLocale.id) {
    _load();
  }

  final _storage = const FlutterSecureStorage();

  Future<void> _load() async {
    final saved = await _storage.read(key: 'locale');
    if (saved == 'en') state = AppLocale.en;
  }

  Future<void> setLocale(AppLocale locale) async {
    state = locale;
    await _storage.write(key: 'locale', value: locale.name);
  }
}

